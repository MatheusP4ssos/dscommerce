-- Schema inicial do DSCommerce (portavel H2/PostgreSQL)

CREATE TABLE tb_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255),
    CONSTRAINT pk_tb_category PRIMARY KEY (id)
);

CREATE TABLE tb_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255),
    description TEXT,
    price NUMERIC(12,2),
    img_url VARCHAR(255),
    CONSTRAINT pk_tb_product PRIMARY KEY (id)
);

CREATE TABLE tb_product_category (
    category_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    CONSTRAINT pk_tb_product_category PRIMARY KEY (category_id, product_id)
);

CREATE TABLE tb_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(255),
    birth_date DATE,
    password VARCHAR(255),
    CONSTRAINT pk_tb_user PRIMARY KEY (id),
    CONSTRAINT uk_tb_user_email UNIQUE (email)
);

CREATE TABLE tb_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    authority VARCHAR(255) NOT NULL,
    CONSTRAINT pk_tb_role PRIMARY KEY (id),
    CONSTRAINT uk_tb_role_authority UNIQUE (authority)
);

CREATE TABLE tb_user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_tb_user_role PRIMARY KEY (user_id, role_id)
);

CREATE TABLE tb_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    moment TIMESTAMP(6) WITH TIME ZONE,
    status VARCHAR(255),
    version BIGINT,
    user_id BIGINT,
    CONSTRAINT pk_tb_order PRIMARY KEY (id)
);

CREATE TABLE tb_payment (
    order_id BIGINT NOT NULL,
    moment TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_tb_payment PRIMARY KEY (order_id)
);

CREATE TABLE tb_order_item (
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER,
    price NUMERIC(12,2),
    CONSTRAINT pk_tb_order_item PRIMARY KEY (order_id, product_id)
);

ALTER TABLE tb_order ADD CONSTRAINT fk_tb_order_user FOREIGN KEY (user_id) REFERENCES tb_user (id);
ALTER TABLE tb_payment ADD CONSTRAINT fk_tb_payment_order FOREIGN KEY (order_id) REFERENCES tb_order (id);
ALTER TABLE tb_order_item ADD CONSTRAINT fk_tb_order_item_order FOREIGN KEY (order_id) REFERENCES tb_order (id);
ALTER TABLE tb_order_item ADD CONSTRAINT fk_tb_order_item_product FOREIGN KEY (product_id) REFERENCES tb_product (id);
ALTER TABLE tb_product_category ADD CONSTRAINT fk_tb_product_category_category FOREIGN KEY (category_id) REFERENCES tb_category (id);
ALTER TABLE tb_product_category ADD CONSTRAINT fk_tb_product_category_product FOREIGN KEY (product_id) REFERENCES tb_product (id);
ALTER TABLE tb_user_role ADD CONSTRAINT fk_tb_user_role_user FOREIGN KEY (user_id) REFERENCES tb_user (id);
ALTER TABLE tb_user_role ADD CONSTRAINT fk_tb_user_role_role FOREIGN KEY (role_id) REFERENCES tb_role (id);
